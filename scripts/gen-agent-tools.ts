// Excerpt from a private codebase, shared for the Make Something Agents Want hackathon (README.md).
// Imports that point outside this folder are not included, so this does not build on its own.

/**
 * Emit `src/agent/tools/generated.ts` from the curation table and the committed
 * OpenAPI snapshot, and `contracts/agent-tools.json` — each tool's severity, for
 * the console's copy table (see `agentToolsContract`).
 *
 * cp-frontend keeps a byte-identical copy of the contract at
 * `test/fixtures/agent-tools.json`, and nothing syncs the two repos: when this
 * run changes the contract, copy it there verbatim and add the console's words
 * for any new tool (cp-frontend `src/lib/agent/tool-copy.ts`).
 *
 * Run with `npm run agent:tools`. Both outputs are committed, and a test
 * (`test/agent/catalogue.test.ts`) re-runs the join in memory and fails if
 * either no longer matches in any field — so a route change that would silently
 * alter a tool's input schema, or a flag flipped in curation.ts, breaks CI
 * instead of reaching a customer's conversation.
 *
 * Why the snapshot and not the live document: importing `src/app.ts` under plain
 * Node fails on `cloudflare:workers`, which `src/db/client.ts` pulls in. The
 * snapshot cannot drift from the app unnoticed: the OpenAPI test fails when the
 * served document differs from it (CI never re-records it), and the catalogue
 * test runs this join against the live document, not the snapshot.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { HANDWRITTEN_TOOL_META } from "../src/agent/tools/handwritten-meta";
import {
  agentToolsContract,
  joinCatalogue,
  type OpenApiDocument,
} from "./agent-tools/catalogue-lib";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const SNAPSHOT = resolve(ROOT, "test/openapi/__snapshots__/openapi.json.snap");
const OUTPUT = resolve(ROOT, "src/agent/tools/generated.ts");
const CONTRACT = resolve(ROOT, "contracts/agent-tools.json");

function loadDocument(): OpenApiDocument {
  return JSON.parse(readFileSync(SNAPSHOT, "utf8")) as OpenApiDocument;
}

function main(): void {
  // The join, and every check that the curation table and the API agree, live
  // in the lib so the catalogue test runs exactly the same code.
  const entries = joinCatalogue(loadDocument());

  const body = `// GENERATED by scripts/gen-agent-tools.ts — do not edit by hand.
//
// Regenerate with \`npm run agent:tools\` after changing
// src/agent/tools/curation.ts or any route's request shape.
// test/agent/catalogue.test.ts fails when this file is stale.

import type { CuratedTool } from "./curation";

export interface ToolMeta extends CuratedTool {
  /** JSON Schema for the tool's arguments. Path/query at top level, body nested. */
  inputSchema: Record<string, unknown>;
  /** Argument names that are substituted into the path template. */
  pathParams: readonly string[];
  /** Argument names that become query-string parameters. */
  queryParams: readonly string[];
}

export const TOOL_META: readonly ToolMeta[] = ${JSON.stringify(entries, null, 2)} as const;

/** Tool metadata by name. */
export const TOOL_BY_NAME: ReadonlyMap<string, ToolMeta> = new Map(
  TOOL_META.map((tool) => [tool.name, tool]),
);
`;

  writeFileSync(OUTPUT, body);
  const contract = agentToolsContract([...entries, ...HANDWRITTEN_TOOL_META.values()]);
  writeFileSync(CONTRACT, `${JSON.stringify(contract, null, 2)}\n`);
  const offered = entries.filter((e) => !e.hidden).length;
  console.log(
    `wrote ${OUTPUT}\n  ${entries.length} tools (${offered} offered, ${entries.length - offered} hidden)\n` +
      `wrote ${CONTRACT}\n` +
      "  if it changed, copy it verbatim to cp-frontend test/fixtures/agent-tools.json",
  );
}

main();
